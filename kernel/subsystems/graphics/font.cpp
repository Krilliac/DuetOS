// Case-insensitive ASCII compare (bounded).
bool StrEqNoCase(const char* a, const char* b, u32 max_len)
{
    for (u32 i = 0; i < max_len; ++i)
    {
        char ca = a[i];
        char cb = b[i];
        if (ca >= 'A' && ca <= 'Z')
            ca = static_cast<char>(ca + 32);
        if (cb >= 'A' && cb <= 'Z')
            cb = static_cast<char>(cb + 32);
        if (ca != cb)
            return false;
        if (ca == '\0')
            return true;
    }
    return true;
}

void StrCopyBounded(char* dst, const char* src, u32 cap)
{
    u32 i = 0;
    for (; i < cap - 1 && src[i] != '\0'; ++i)
        dst[i] = src[i];
    dst[i] = '\0';
}

